// Package sqlite предоставляет реализацию слоя доступа к данным (DAL) для СУБД SQLite.
// Он содержит логику маппинга доменных моделей на SQL-запросы и специфичные для
// SQLite утилиты обработки данных.
package sqlite

import (
	"errors"
	"strings"
	"time"
)

// parseSQLiteTime бережно распознает различные строковые форматы даты и времени,
// возвращаемые SQLite при выполнении запросов.
// Функция является внутренней (неэкспортируемой) и доступна только внутри пакета sqlite.
func parseSQLiteTime(s string) (time.Time, error) {
	s = strings.TrimSpace(s)

	// Отрезаем внутреннюю монотонную составляющую Go (m=+...),
	// если она была некорректно записана или считана из БД.
	if idx := strings.LastIndex(s, " m="); idx != -1 {
		s = s[:idx]
	}

	formats := []string{
		"2006-01-02 15:04:05.999999999 -0700 MST",
		"2006-01-02 15:04:05.999999999 -0700 UTC",
		"2006-01-02 15:04:05.999999999-07:00",
		"2006-01-02 15:04:05.999999999",
		"2006-01-02 15:04:05",
		time.RFC3339,
		"2006-01-02T15:04:05Z07:00",
	}

	for _, f := range formats {
		if t, err := time.Parse(f, s); err == nil {
			return t, nil
		}
	}
	return time.Time{}, errors.New("неизвестный формат времени SQLite: " + s)
}
